require("luacov")
package.preload["ui"] = function()
    return {
        printer = { line = function() end, raw = function() end },
        security_prompt = { confirm_execution = function() return true end },
        input = { read_line = function() return "" end },
    }
end
package.preload["utils"] = function()
    return {
        trim = function(s)
            if not s then return "" end
            return s:match("^%s*(.-)%s*$") or ""
        end,
    }
end
local shell_module = require("tools.shell")
local captured = {}
do
    local mock_registry = {
        register = function(name, desc, usage, h, ms_doc, man)
            captured.handler = h
            captured.manifest = man
            captured.name = name
            captured.desc = desc
        end
    }
    shell_module.register(mock_registry)
end
local handler = captured.handler
local manifest = captured.manifest
describe("Shell Tool", function()
    describe("Module structure", function()
        it("exports register function", function()
            assert.is_function(shell_module.register)
        end)
    end)
    describe("Registration", function()
        it("registers under name 'shell'", function()
            assert.are.equal("shell", captured.name)
        end)
        it("provides description mentioning timeout", function()
            assert.truthy(captured.desc:find("interactive"))
        end)
    end)
    describe("Manifest", function()
        it("has is_mutation = false", function()
            assert.is_false(manifest.is_mutation)
        end)
        it("has validate_payload function", function()
            assert.is_function(manifest.validate_payload)
        end)
        it("has estimate_complexity function", function()
            assert.is_function(manifest.estimate_complexity)
        end)
        it("has enrich_result function", function()
            assert.is_function(manifest.enrich_result)
        end)
        it("has intent_guideline string", function()
            assert.is_string(manifest.intent_guideline)
            assert.truthy(#manifest.intent_guideline > 0)
        end)
    end)
    describe("Manifest validate_payload", function()
        it("rejects nil payload", function()
            local ok, err = manifest.validate_payload(nil)
            assert.is_false(ok)
            assert.truthy(err:find("empty"))
        end)
        it("rejects empty string", function()
            local ok, err = manifest.validate_payload("")
            assert.is_false(ok)
            assert.truthy(err:find("empty"))
        end)
        it("rejects whitespace-only string", function()
            local ok, err = manifest.validate_payload("   ")
            assert.is_false(ok)
            assert.truthy(err:find("empty"))
        end)
        it("accepts valid command", function()
            local ok = manifest.validate_payload("ls -la")
            assert.is_true(ok)
        end)
    end)
    describe("Manifest estimate_complexity", function()
        it("returns 'complex'", function()
            assert.are.equal("complex", manifest.estimate_complexity())
        end)
    end)
    describe("Manifest enrich_result", function()
        it("returns input unchanged", function()
            assert.are.equal("some output", manifest.enrich_result("some output"))
        end)
        it("handles empty string", function()
            assert.are.equal("", manifest.enrich_result(""))
        end)
    end)
    describe("Handler behavior", function()
        it("returns message for empty command", function()
            local result = handler("   ", {}, "TEST")
            assert.truthy(result.output:find("No command provided"))
        end)
        it("executes simple command and captures output", function()
            local result = handler("echo hello_world_test", {}, "TEST")
            assert.truthy(result.output:find("hello_world_test"))
            assert.truthy(result.output:find("SHELL STDOUT/STDERR"))
        end)
        it("captures stderr output", function()
            local result = handler("echo error_msg 1>&2", {}, "TEST")
            assert.truthy(result.output:find("error_msg"))
        end)
        it("reports silent command with exit code 0", function()
            local result = handler("true", {}, "TEST")
            assert.truthy(result.output:find("silently"))
            assert.truthy(result.output:find("Status: 0"))
        end)
        it("reports non-zero exit code for silent command", function()
            local result = handler("false", {}, "TEST")
            assert.truthy(result.output:find("silently"))
            assert.truthy(result.output:find("Status: 1"))
        end)
    end)
    describe("Circuit breaker", function()
        it("increments test_failures on failing test command", function()
            local ctx = { test_failures = 0 }
            handler("bash -c 'echo test Fail; exit 1'", ctx, "TEST")
            assert.are.equal(1, ctx.test_failures)
        end)
        it("resets test_failures on success", function()
            local ctx = { test_failures = 2 }
            handler("bash -c 'echo test all good'", ctx, "TEST")
            assert.are.equal(0, ctx.test_failures)
        end)
        it("triggers circuit breaker at 3 consecutive failures", function()
            local ctx = { test_failures = 2 }
            local result = handler("bash -c 'echo test Fail; exit 1'", ctx, "TEST")
            assert.truthy(result.output:find("CIRCUIT BREAKER"))
            assert.are.equal(0, ctx.test_failures)
        end)
        it("does not track failures for non-test commands", function()
            local ctx = { test_failures = 0 }
            handler("bash -c 'exit 1'", ctx, "TEST")
            assert.are.equal(0, ctx.test_failures)
        end)
    end)
    describe("Output formatting", function()
        it("wraps output in SHELL STDOUT/STDERR header", function()
            local result = handler("echo formatted", {}, "TEST")
            assert.truthy(result.output:find("[SHELL STDOUT/STDERR]"))
        end)
        it("handles multi-line output", function()
            local result = handler("printf 'line1\\nline2\\nline3'", {}, "TEST")
            assert.truthy(result.output:find("line1"))
            assert.truthy(result.output:find("line2"))
            assert.truthy(result.output:find("line3"))
        end)
    end)
end)
