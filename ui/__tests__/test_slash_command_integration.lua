describe("Slash Command Integration - Full Pipeline Dispatch", function()
    local command_parser = require("ui.command_parser")
    local strings = require("utils.strings")
    local pipeline_ui = require("ui.pipeline_ui")
    -- Simulate the EXACT dispatch logic from agent/pipeline.lua lines 77-130
    local function simulate_full_dispatch(user_input, config)
        if not user_input or strings.trim(user_input) == "" or strings.trim(user_input) == "/exit" then
            return { handled = true, action = "ABORT_DIRECT", reason = "Early exit check" }
        end
        local cmd = pipeline_ui.parse_command(user_input, config)
        if cmd.action == "NEXT_STAGE" then
            return { handled = true, action = "NEXT_STAGE", message = cmd.message }
        elseif cmd.action == "PREV_STAGE" then
            return { handled = true, action = "PREV_STAGE", message = cmd.message }
        elseif cmd.action == "SWITCH_STAGE" then
            return { handled = true, action = "SWITCH_STAGE", target_idx = cmd.target_idx, message = cmd.message }
        elseif cmd.action == "STATUS" then
            return { handled = true, action = "STATUS", message = cmd.message }
        elseif cmd.action == "HELP" then
            return { handled = true, action = "HELP", message = cmd.message }
        elseif cmd.action == "ABORT" then
            return { handled = true, action = "ABORT", message = cmd.message }
        elseif cmd.action == "SKIP" then
            return { handled = true, action = "SKIP", message = cmd.message }
        elseif cmd.action == "ERROR" then
            return { handled = true, action = "ERROR", message = cmd.message }
        elseif cmd.action == "MESSAGE" and strings.trim(user_input) ~= "" then
            return { handled = true, action = "MESSAGE", message = user_input }
        else
            return { handled = false, action = cmd.action, message = cmd.message }
        end
    end
    describe("CRITICAL: Real-world TTY input edge cases", function()
        it("should handle /go with Windows-style CRLF", function()
            local result = simulate_full_dispatch("/go\r\n", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle /go with bare CR", function()
            local result = simulate_full_dispatch("/go\r", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle /status with trailing CRLF", function()
            local result = simulate_full_dispatch("/status\r\n", nil)
            assert.is_true(result.handled)
            assert.equals("STATUS", result.action)
        end)
        it("should handle /back with mixed whitespace", function()
            local result = simulate_full_dispatch("  /back  \r\n", nil)
            assert.is_true(result.handled)
            assert.equals("PREV_STAGE", result.action)
        end)
        it("should handle /exit with CRLF (early check)", function()
            local result = simulate_full_dispatch("/exit\r\n", nil)
            assert.is_true(result.handled)
            assert.equals("ABORT_DIRECT", result.action)
        end)
        it("should handle /help with tab and newline", function()
            local result = simulate_full_dispatch("\t/help\n", nil)
            assert.is_true(result.handled)
            assert.equals("HELP", result.action)
        end)
    end)
    describe("Multiline input scenarios (Enter then Ctrl+D)", function()
        it("should treat /go on first line as command even with extra lines below", function()
            local result = simulate_full_dispatch("/go\nsome extra text", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle command on first line with empty second line", function()
            local result = simulate_full_dispatch("/go\n", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle command with trailing blank lines", function()
            local result = simulate_full_dispatch("/status\n\n", nil)
            assert.is_true(result.handled)
            assert.equals("STATUS", result.action)
        end)
    end)
    describe("Unicode and special character resilience", function()
        it("should handle cyrillic text as MESSAGE", function()
            local result = simulate_full_dispatch("привет мир", nil)
            assert.is_true(result.handled)
            assert.equals("MESSAGE", result.action)
        end)
        it("should handle /go with zero-width spaces", function()
            local result = simulate_full_dispatch("/go", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
    end)
    describe("strings.trim() boundary conditions", function()
        it("should trim LF", function()
            assert.equals("/go", strings.trim("/go\n"))
        end)
        it("should trim CR", function()
            assert.equals("/go", strings.trim("/go\r"))
        end)
        it("should trim CRLF", function()
            assert.equals("/go", strings.trim("/go\r\n"))
        end)
        it("should trim multiple whitespace types", function()
            assert.equals("/go", strings.trim("\t \n /go \r\n\t"))
        end)
        it("should handle nil gracefully", function()
            assert.equals("", strings.trim(nil))
        end)
        it("should handle empty string", function()
            assert.equals("", strings.trim(""))
        end)
    end)
    describe("command_parser.parse() exact match verification", function()
        it("should match /go exactly after trim", function()
            local result = command_parser.parse("/go", nil)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should NOT match /go_extra (different command)", function()
            local result = command_parser.parse("/go_extra", nil)
            assert.equals("MESSAGE", result.action)
        end)
        it("should NOT match /goto (different command)", function()
            local result = command_parser.parse("/goto", nil)
            assert.equals("MESSAGE", result.action)
        end)
        it("should NOT match /status_extra (different command)", function()
            local result = command_parser.parse("/status_extra", nil)
            assert.equals("MESSAGE", result.action)
        end)
        it("should handle /mode with single space separator", function()
            local config = { PIPELINE = { { stage = "CODER", mode = "sequential" } } }
            local result = command_parser.parse("/mode CODER", config)
            assert.equals("SWITCH_STAGE", result.action)
        end)
        it("should handle /mode with multiple spaces", function()
            local config = { PIPELINE = { { stage = "CODER", mode = "sequential" } } }
            local result = command_parser.parse("/mode   CODER", config)
            assert.equals("SWITCH_STAGE", result.action)
        end)
    end)
    describe("Full pipeline dispatch - all actions covered", function()
        local config = {
            PIPELINE = {
                { stage = "ARCHITECT", mode = "interactive" },
                { stage = "CODER", mode = "sequential" },
                { stage = "REVIEWER", mode = "sequential" },
            }
        }
        it("dispatches /go -> NEXT_STAGE", function()
            assert.equals("NEXT_STAGE", simulate_full_dispatch("/go", config).action)
        end)
        it("dispatches /back -> PREV_STAGE", function()
            assert.equals("PREV_STAGE", simulate_full_dispatch("/back", config).action)
        end)
        it("dispatches /exit -> ABORT_DIRECT (early check)", function()
            assert.equals("ABORT_DIRECT", simulate_full_dispatch("/exit", config).action)
        end)
        it("dispatches /status -> STATUS", function()
            assert.equals("STATUS", simulate_full_dispatch("/status", config).action)
        end)
        it("dispatches /help -> HELP", function()
            assert.equals("HELP", simulate_full_dispatch("/help", config).action)
        end)
        it("dispatches /mode CODER -> SWITCH_STAGE", function()
            local r = simulate_full_dispatch("/mode CODER", config)
            assert.equals("SWITCH_STAGE", r.action)
            assert.equals(2, r.target_idx)
        end)
        it("dispatches /mode UNKNOWN -> ERROR", function()
            assert.equals("ERROR", simulate_full_dispatch("/mode UNKNOWN", config).action)
        end)
        it("dispatches empty -> ABORT_DIRECT", function()
            assert.equals("ABORT_DIRECT", simulate_full_dispatch("", config).action)
        end)
        it("dispatches nil -> ABORT_DIRECT", function()
            assert.equals("ABORT_DIRECT", simulate_full_dispatch(nil, config).action)
        end)
        it("dispatches whitespace -> ABORT_DIRECT", function()
            assert.equals("ABORT_DIRECT", simulate_full_dispatch("   ", config).action)
        end)
        it("dispatches regular text -> MESSAGE", function()
            assert.equals("MESSAGE", simulate_full_dispatch("hello", config).action)
        end)
    end)
    describe("Potential bug: input.read_text return values", function()
        it("should handle return value with leading newline", function()
            local result = simulate_full_dispatch("\n/go", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle return value that is just newlines", function()
            local result = simulate_full_dispatch("\n\n\n", nil)
            assert.is_true(result.handled)
            assert.equals("ABORT_DIRECT", result.action)
        end)
    end)
    describe("BUG FIX: Multiline duplication handling", function()
        it("should handle /go\\n/go duplication (user pressed Enter then typed again)", function()
            local result = simulate_full_dispatch("/go\n/go", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle /status\\n/status duplication", function()
            local result = simulate_full_dispatch("/status\n/status", nil)
            assert.is_true(result.handled)
            assert.equals("STATUS", result.action)
        end)
        it("should handle /back\\n/back duplication", function()
            local result = simulate_full_dispatch("/back\n/back", nil)
            assert.is_true(result.handled)
            assert.equals("PREV_STAGE", result.action)
        end)
        it("should handle /help\\n/help duplication", function()
            local result = simulate_full_dispatch("/help\n/help", nil)
            assert.is_true(result.handled)
            assert.equals("HELP", result.action)
        end)
        it("should handle /exit\\n/exit duplication (falls to parser)", function()
            local result = simulate_full_dispatch("/exit\n/exit", nil)
            assert.is_true(result.handled)
            assert.equals("ABORT", result.action)
        end)
        it("should handle /go with CRLF duplication", function()
            local result = simulate_full_dispatch("/go\r\n/go", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle /mode CODER duplication", function()
            local config = { PIPELINE = { { stage = "CODER", mode = "sequential" } } }
            local result = simulate_full_dispatch("/mode CODER\n/mode CODER", config)
            assert.is_true(result.handled)
            assert.equals("SWITCH_STAGE", result.action)
        end)
        it("should handle triple duplication /go\\n/go\\n/go", function()
            local result = simulate_full_dispatch("/go\n/go\n/go", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle command on first line with garbage on second", function()
            local result = simulate_full_dispatch("/go\nrandom garbage", nil)
            assert.is_true(result.handled)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should still treat multiline text as MESSAGE when no command on first line", function()
            local result = simulate_full_dispatch("hello world\nsecond line", nil)
            assert.is_true(result.handled)
            assert.equals("MESSAGE", result.action)
        end)
    end)
end)
