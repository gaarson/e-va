describe("Command Parser", function()
    local command_parser = require("ui.command_parser")
    local strings = require("utils.strings")
    describe("COMMANDS table", function()
        it("should define all expected commands", function()
            assert.equals("NEXT_STAGE", command_parser.COMMANDS["/go"])
            assert.equals("PREV_STAGE", command_parser.COMMANDS["/back"])
            assert.equals("ABORT", command_parser.COMMANDS["/exit"])
            assert.equals("STATUS", command_parser.COMMANDS["/status"])
            assert.equals("HELP", command_parser.COMMANDS["/help"])
        end)
    end)
    describe("parse() - basic commands", function()
        it("should parse /go as NEXT_STAGE", function()
            local result = command_parser.parse("/go", nil)
            assert.equals("NEXT_STAGE", result.action)
            assert.is_not_nil(result.message)
        end)
        it("should parse /back as PREV_STAGE", function()
            local result = command_parser.parse("/back", nil)
            assert.equals("PREV_STAGE", result.action)
        end)
        it("should parse /exit as ABORT", function()
            local result = command_parser.parse("/exit", nil)
            assert.equals("ABORT", result.action)
        end)
        it("should parse /status as STATUS", function()
            local result = command_parser.parse("/status", nil)
            assert.equals("STATUS", result.action)
        end)
        it("should parse /help as HELP", function()
            local result = command_parser.parse("/help", nil)
            assert.equals("HELP", result.action)
            assert.is_not_nil(result.message)
        end)
    end)
    describe("parse() - whitespace handling", function()
        it("should handle leading whitespace", function()
            local result = command_parser.parse("  /go", nil)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle trailing whitespace", function()
            local result = command_parser.parse("/go  ", nil)
            assert.equals("NEXT_STAGE", result.action)
        end)
        it("should handle both leading and trailing whitespace", function()
            local result = command_parser.parse("  /status  ", nil)
            assert.equals("STATUS", result.action)
        end)
        it("should handle tabs around command", function()
            local result = command_parser.parse("\t/back\t", nil)
            assert.equals("PREV_STAGE", result.action)
        end)
        it("should handle /exit with trailing space", function()
            local result = command_parser.parse("/exit ", nil)
            assert.equals("ABORT", result.action)
        end)
        it("should handle /exit with leading space", function()
            local result = command_parser.parse(" /exit", nil)
            assert.equals("ABORT", result.action)
        end)
    end)
    describe("parse() - edge cases", function()
        it("should return ABORT for nil input", function()
            local result = command_parser.parse(nil, nil)
            assert.equals("ABORT", result.action)
        end)
        it("should return SKIP for empty string", function()
            local result = command_parser.parse("", nil)
            assert.equals("SKIP", result.action)
        end)
        it("should return SKIP for whitespace-only input", function()
            local result = command_parser.parse("   ", nil)
            assert.equals("SKIP", result.action)
        end)
        it("should return MESSAGE for regular text", function()
            local result = command_parser.parse("hello world", nil)
            assert.equals("MESSAGE", result.action)
            assert.equals("hello world", result.message)
        end)
        it("should return MESSAGE for unknown slash commands", function()
            local result = command_parser.parse("/unknown", nil)
            assert.equals("MESSAGE", result.action)
            assert.equals("/unknown", result.message)
        end)
    end)
    describe("parse() - /mode command", function()
        local config_with_pipeline = {
            PIPELINE = {
                { stage = "ARCHITECT", mode = "interactive" },
                { stage = "CODER", mode = "sequential" },
                { stage = "REVIEWER", mode = "sequential" },
            }
        }
        it("should parse /mode ARCHITECT as SWITCH_STAGE", function()
            local result = command_parser.parse("/mode ARCHITECT", config_with_pipeline)
            assert.equals("SWITCH_STAGE", result.action)
            assert.equals(1, result.target_idx)
        end)
        it("should parse /mode CODER as SWITCH_STAGE", function()
            local result = command_parser.parse("/mode CODER", config_with_pipeline)
            assert.equals("SWITCH_STAGE", result.action)
            assert.equals(2, result.target_idx)
        end)
        it("should parse /mode REVIEWER as SWITCH_STAGE", function()
            local result = command_parser.parse("/mode REVIEWER", config_with_pipeline)
            assert.equals("SWITCH_STAGE", result.action)
            assert.equals(3, result.target_idx)
        end)
        it("should return ERROR for unknown stage", function()
            local result = command_parser.parse("/mode UNKNOWN", config_with_pipeline)
            assert.equals("ERROR", result.action)
        end)
        it("should handle /mode with extra whitespace", function()
            local result = command_parser.parse("  /mode   CODER  ", config_with_pipeline)
            assert.equals("SWITCH_STAGE", result.action)
            assert.equals(2, result.target_idx)
        end)
        it("should handle /mode without config", function()
            local result = command_parser.parse("/mode CODER", nil)
            assert.equals("ERROR", result.action)
        end)
    end)
    describe("parse() - HELP text content", function()
        it("should return HELP_TEXT in message for /help", function()
            local result = command_parser.parse("/help", nil)
            assert.equals(command_parser.HELP_TEXT, result.message)
            assert.is_not_nil(string.find(command_parser.HELP_TEXT, "/go"))
            assert.is_not_nil(string.find(command_parser.HELP_TEXT, "/back"))
            assert.is_not_nil(string.find(command_parser.HELP_TEXT, "/exit"))
            assert.is_not_nil(string.find(command_parser.HELP_TEXT, "/status"))
        end)
    end)
    describe("strings.trim() - dependency verification", function()
        it("should trim leading spaces", function()
            assert.equals("hello", strings.trim("  hello"))
        end)
        it("should trim trailing spaces", function()
            assert.equals("hello", strings.trim("hello  "))
        end)
        it("should trim both sides", function()
            assert.equals("hello", strings.trim("  hello  "))
        end)
        it("should handle nil", function()
            assert.equals("", strings.trim(nil))
        end)
        it("should handle empty string", function()
            assert.equals("", strings.trim(""))
        end)
        it("should handle tabs and newlines", function()
            assert.equals("hello", strings.trim("\thello\n"))
        end)
    end)
end)
