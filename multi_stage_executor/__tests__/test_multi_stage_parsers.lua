describe("Multi-Stage Parsers", function()
    local parsers = require("multi_stage_executor.parsers")
    describe("sanitize_payload()", function()
        it("should strip surrounding backtick fences", function()
            local raw = "```lua\nhello world\n```"
            local result = parsers.sanitize_payload(raw)
            assert.equals("hello world", result)
        end)
        it("should strip backtick fences without language tag", function()
            local raw = "```\ntool_name:args\n```"
            local result = parsers.sanitize_payload(raw)
            assert.equals("tool_name:args", result)
        end)
        it("should strip preamble text", function()
            local raw = "Here is the payload:\ntool_name:args"
            local result = parsers.sanitize_payload(raw)
            assert.equals("tool_name:args", result)
        end)
        it("should strip ||| COMMAND ||| markers", function()
            local raw = "||| COMMAND |||\ntool_name:args\n||| END_COMMAND |||"
            local result = parsers.sanitize_payload(raw)
            assert.equals("tool_name:args", result)
        end)
        it("should handle nil input", function()
            local result = parsers.sanitize_payload(nil)
            assert.equals("", result)
        end)
        it("should handle empty input", function()
            local result = parsers.sanitize_payload("")
            assert.equals("", result)
        end)
        it("should trim whitespace", function()
            local raw = "  tool_name:args  "
            local result = parsers.sanitize_payload(raw)
            assert.equals("tool_name:args", result)
        end)
        it("should handle combined fences + markers", function()
            local raw = "```\n||| COMMAND |||\ntool_name:args\n||| END_COMMAND |||\n```"
            local result = parsers.sanitize_payload(raw)
            assert.equals("tool_name:args", result)
        end)
    end)
    describe("render()", function()
        it("should substitute variables", function()
            local template = "Hello {name}, you are {role}"
            local result = parsers.render(template, { name = "Alice", role = "admin" })
            assert.equals("Hello Alice, you are admin", result)
        end)
        it("should leave unknown keys as-is", function()
            local template = "Hello {name}"
            local result = parsers.render(template, {})
            assert.equals("Hello {name}", result)
        end)
        it("should handle nil vars table", function()
            local template = "Hello {name}"
            local result = parsers.render(template, nil)
            assert.equals("Hello {name}", result)
        end)
    end)
    describe("extract_field()", function()
        it("should extract a simple field", function()
            local block = "GOAL: Fix the bug\nTOOL: patch"
            assert.equals("Fix the bug", parsers.extract_field(block, "GOAL"))
            assert.equals("patch", parsers.extract_field(block, "TOOL"))
        end)
        it("should handle case-insensitive field names", function()
            local block = "goal: Fix the bug\ntool: patch"
            assert.equals("Fix the bug", parsers.extract_field(block, "GOAL"))
        end)
        it("should return empty string for missing field", function()
            local block = "GOAL: Fix the bug"
            assert.equals("", parsers.extract_field(block, "TOOL"))
        end)
        it("should handle nil block", function()
            assert.equals("", parsers.extract_field(nil, "GOAL"))
        end)
        it("should handle nil name", function()
            assert.equals("", parsers.extract_field("GOAL: test", nil))
        end)
        it("should handle multi-line field values", function()
            local block = "GOAL: Fix the bug\nthat is on line 5\nTOOL: patch"
            local result = parsers.extract_field(block, "GOAL")
            assert.equals("Fix the bug\nthat is on line 5", result)
        end)
    end)
    describe("summarize_correction()", function()
        it("should return short text as-is", function()
            local text = "Fix the typo on line 5"
            assert.equals(text, parsers.summarize_correction(text))
        end)
        it("should truncate long text", function()
            local text = string.rep("x", 600)
            local result = parsers.summarize_correction(text)
            assert.is_true(#result <= 503) -- 500 + "..."
            assert.is_true(result:sub(-3) == "...")
        end)
        it("should truncate at period boundary", function()
            -- Place period near the truncation boundary so the function can find it
            local text = string.rep("x", 485) .. ". Final word. " .. string.rep("y", 30)
            local result = parsers.summarize_correction(text)
            assert.is_true(#result <= 503)  -- 500 chars + "..."
            assert.is_true(result:sub(-3) == "...")
        end)
    end)
    describe("estimate_complexity()", function()
        it("should classify delegate_plan as complex", function()
            assert.equals("complex", parsers.estimate_complexity("delegate_plan", "", nil))
        end)
        it("should classify shell as complex", function()
            assert.equals("complex", parsers.estimate_complexity("shell", "", nil))
        end)
        it("should classify simple extension + small payload as simple", function()
            -- create_file with .md (simple ext) and "small" keyword => simple
            local result = parsers.estimate_complexity("create_file", "small change", "test.md")
            assert.equals("simple", result)
        end)
        it("should classify create_file with simple ext and no hint as simple", function()
            -- create_file with .json (simple ext) alone => simple
            assert.equals("simple", parsers.estimate_complexity("create_file", "", "test.json"))
        end)
        it("should classify create_file with simple ext as simple", function()
            assert.equals("simple", parsers.estimate_complexity("create_file", "", "test.json"))
        end)
        it("should classify unknown tool as complex by default", function()
            assert.equals("complex", parsers.estimate_complexity("unknown_tool", "", "test.lua"))
        end)
        it("should detect complex keywords in hint", function()
            assert.equals("complex", parsers.estimate_complexity("patch", "refactor the entire module", "test.lua"))
        end)
    end)
    describe("validate_payload()", function()
        it("should reject empty payload", function()
            local ok, err = parsers.validate_payload("shell", "")
            assert.is_false(ok)
        end)
        it("should reject nil payload", function()
            local ok, err = parsers.validate_payload("shell", nil)
            assert.is_false(ok)
        end)
        it("should accept non-empty payload", function()
            local ok, err = parsers.validate_payload("shell", "ls -la")
            assert.is_true(ok)
        end)
        it("should reject whitespace-only payload", function()
            local ok, err = parsers.validate_payload("shell", "   ")
            assert.is_false(ok)
        end)
    end)
end)
