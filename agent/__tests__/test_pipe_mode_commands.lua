describe("Pipe Mode Command Dispatch", function()
    local command_parser = require("ui.command_parser")
    it("should parse /messages as MESSAGES action", function()
        local result = command_parser.parse("/messages", nil)
        assert.equals("MESSAGES", result.action)
    end)
    it("should parse /status as STATUS action", function()
        local result = command_parser.parse("/status", nil)
        assert.equals("STATUS", result.action)
    end)
    it("should parse /help as HELP action", function()
        local result = command_parser.parse("/help", nil)
        assert.equals("HELP", result.action)
    end)
    it("should parse /exit as ABORT action", function()
        local result = command_parser.parse("/exit", nil)
        assert.equals("ABORT", result.action)
    end)
    it("should parse /quit as ABORT action", function()
        local result = command_parser.parse("/quit", nil)
        assert.equals("ABORT", result.action)
    end)
    it("should parse /go as NEXT_STAGE (not available in pipe)", function()
        local result = command_parser.parse("/go", nil)
        assert.equals("NEXT_STAGE", result.action)
    end)
    it("should parse /back as PREV_STAGE (not available in pipe)", function()
        local result = command_parser.parse("/back", nil)
        assert.equals("PREV_STAGE", result.action)
    end)
    it("should parse /discard as DISCARD action", function()
        local result = command_parser.parse("/discard", nil)
        assert.equals("DISCARD", result.action)
    end)
    it("should parse non-slash input as MESSAGE action", function()
        local result = command_parser.parse("fix the bug in main.lua", nil)
        assert.equals("MESSAGE", result.action)
        assert.equals("fix the bug in main.lua", result.message)
    end)
    it("should parse unknown /command as MESSAGE action", function()
        local result = command_parser.parse("/unknown_command", nil)
        assert.equals("MESSAGE", result.action)
    end)
    it("should handle whitespace-padded commands", function()
        local result = command_parser.parse("  /messages  ", nil)
        assert.equals("MESSAGES", result.action)
    end)
    it("should parse /mode with valid stage as SWITCH_STAGE", function()
        local config = { PIPELINE = { { stage = "CODER" }, { stage = "REVIEWER" } } }
        local result = command_parser.parse("/mode CODER", config)
        assert.equals("SWITCH_STAGE", result.action)
        assert.equals(1, result.target_idx)
    end)
    it("should parse /mode with invalid stage as ERROR", function()
        local config = { PIPELINE = { { stage = "CODER" } } }
        local result = command_parser.parse("/mode GHOST", config)
        assert.equals("ERROR", result.action)
    end)
end)
