describe("Interruption Command Dispatch", function()
    local command_parser = require("ui.command_parser")
    it("should parse /discard as DISCARD", function()
        local result = command_parser.parse("/discard", nil)
        assert.equals("DISCARD", result.action)
    end)
    it("should parse /messages as MESSAGES", function()
        local result = command_parser.parse("/messages", nil)
        assert.equals("MESSAGES", result.action)
    end)
    it("should parse /status as STATUS", function()
        local result = command_parser.parse("/status", nil)
        assert.equals("STATUS", result.action)
    end)
    it("should parse /help as HELP", function()
        local result = command_parser.parse("/help", nil)
        assert.equals("HELP", result.action)
    end)
    it("should parse /exit as ABORT", function()
        local result = command_parser.parse("/exit", nil)
        assert.equals("ABORT", result.action)
    end)
    it("should parse regular text as MESSAGE (correction)", function()
        local result = command_parser.parse("actually, please use a different approach", nil)
        assert.equals("MESSAGE", result.action)
        assert.equals("actually, please use a different approach", result.message)
    end)
    it("should parse empty string as SKIP", function()
        local result = command_parser.parse("", nil)
        assert.equals("SKIP", result.action)
    end)
    it("should handle multiline input - first line determines action", function()
        local nl = string.char(10)
        local result = command_parser.parse("/discard" .. nl .. "extra text here", nil)
        assert.equals("DISCARD", result.action)
    end)
    it("should handle multiline non-command input as MESSAGE with full text", function()
        local nl = string.char(10)
        local input = "please fix the bug" .. nl .. "it is in line 42"
        local result = command_parser.parse(input, nil)
        assert.equals("MESSAGE", result.action)
        assert.truthy(result.message:find("please fix the bug"))
        assert.truthy(result.message:find("line 42"))
    end)
    it("should handle /discard with trailing whitespace", function()
        local result = command_parser.parse("/discard   ", nil)
        assert.equals("DISCARD", result.action)
    end)
    it("should handle /messages with trailing whitespace", function()
        local result = command_parser.parse("  /messages  ", nil)
        assert.equals("MESSAGES", result.action)
    end)
end)
